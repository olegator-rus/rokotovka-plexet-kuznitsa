const fmt = (n: number, d = 3) => n.toFixed(d).replace('.', ',')

/** Пример расчёта RRF: места товаров в двух списках (null — товара в списке нет). */
const EXAMPLE = (() => {
  const k = P.rrfK
  const rows = [
    { name: 'Товар 1', bm25: 1, dense: 2 },
    { name: 'Товар 2', bm25: 3, dense: 3 },
    { name: 'Товар 3', bm25: null, dense: 1 },
    { name: 'Товар 4', bm25: 2, dense: null },
  ].map((r) => {
    const a = r.bm25 ? 1 / (k + r.bm25) : 0
    const b = r.dense ? 1 / (k + r.dense) : 0
    return { ...r, a, b, sum: a + b }
  })
  const best = Math.max(...rows.map((r) => r.sum))
  return rows.map((r) => ({ ...r, rel: r.sum / best })).sort((x, y) => y.sum - x.sum)
})()

/** Пояснение к одной строке примера: «Товар 2» нигде не выше третьего, но обходит первый номер векторов. */
const RRF_NOTE = (() => {
  const k = P.rrfK
  const pos = (name: string) => EXAMPLE.findIndex((r) => r.name === name)
  const t2 = EXAMPLE[pos('Товар 2')]
  const t3 = EXAMPLE[pos('Товар 3')]
  if (!t2 || !t3) return ''
  return (
    `«Товар 2» в обоих списках на ${t2.bm25}-м месте, а в общем он ${pos('Товар 2') + 1}-й: ` +
    `1/${k + (t2.bm25 ?? 0)} + 1/${k + (t2.dense ?? 0)} = ${fmt(t2.sum, 4)}. «Товар 3» у векторов ` +
    `на ${t3.dense}-м месте, но в текстовом списке его нет, и слагаемое у него одно: ` +
    `1/${k + (t3.dense ?? 0)} = ${fmt(t3.sum, 4)}. Два средних места оказались весомее одного первого.`
  )
})()

/** Насколько первое место весомее десятого при k для B3 и для B2. */
