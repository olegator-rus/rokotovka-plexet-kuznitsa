const fmt = (n: number, d = 3) => n.toFixed(d).replace('.', ',')

/** Пример расчёта RRF: места товаров в двух списках (null — товара в списке нет). */
const EXAMPLE = (() => {
  const k = P.rrfK
  const rows = [
    { name: 'Товар 1', bm25: 1, dense: 2 },
    { name: 'Товар 2', bm25: 3, dense: 3 },
    { name: 'Товар 3', bm25: null, dense: 1 },
    { name: 'Товар 4', bm25: 2, dense: null },
  ].map((r) => {
    const a = r.bm25 ? 1 / (k + r.bm25) : 0
    const b = r.dense ? 1 / (k + r.dense) : 0
    return { ...r, a, b, sum: a + b }
  })
  const best = Math.max(...rows.map((r) => r.sum))
  return rows.map((r) => ({ ...r, rel: r.sum / best })).sort((x, y) => y.sum - x.sum)
})()

/** Насколько первое место весомее десятого при k для B3 и для B2. */
const ratio = (k: number) => ru(Number(((k + 10) / (k + 1)).toFixed(2)))

